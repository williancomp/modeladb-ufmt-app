/** Writers for result tables: every table is emitted as CSV and as a LaTeX tabular fragment. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './pipeline.mjs';

export const RESULTS_DIR = process.env.EVAL_RESULTS_DIR || join(ROOT, 'evaluation', 'results');
export const LOGS_DIR = join(RESULTS_DIR, 'logs');

const csvCell = (value) => {
  const text = value === null || value === undefined ? '' : String(value);
  return /[",\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
};

const latexEscape = (value) =>
  String(value ?? '')
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');

/** rows: array of objects with identical keys. columns: [{key, header, align}] (defaults to the keys). */
export function writeTable(name, rows, columns, { caption = '', note = '' } = {}) {
  mkdirSync(RESULTS_DIR, { recursive: true });
  const cols = columns || Object.keys(rows[0] || {}).map((key) => ({ key, header: key }));
  const csv = [cols.map((c) => csvCell(c.header)).join(','), ...rows.map((r) => cols.map((c) => csvCell(r[c.key])).join(','))].join('\n');
  writeFileSync(join(RESULTS_DIR, `${name}.csv`), `${csv}\n`);
  const align = cols.map((c) => c.align || 'l').join('');
  const body = rows.map((r) => `${cols.map((c) => latexEscape(r[c.key])).join(' & ')} \\\\`).join('\n');
  const tex = [
    `% Generated by evaluation/run.mjs - do not edit. ${caption}`,
    `\\begin{tabular}{${align}}`,
    '\\hline',
    `${cols.map((c) => `\\textbf{${latexEscape(c.header)}}`).join(' & ')} \\\\`,
    '\\hline',
    body,
    '\\hline',
    '\\end{tabular}',
    note ? `% ${note}` : '',
  ].join('\n');
  writeFileSync(join(RESULTS_DIR, `${name}.tex`), `${tex}\n`);
}

export function writeLog(name, text) {
  mkdirSync(LOGS_DIR, { recursive: true });
  // Absolute checkout paths differ between machines; keep them out of the logs.
  const portable = text.replaceAll(ROOT, '<repo>');
  writeFileSync(join(LOGS_DIR, name), portable.endsWith('\n') ? portable : `${portable}\n`);
}

/** Deterministic seeded PRNG (mulberry32). */
export function prng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
